import { describe, expect, it } from "vitest";
import { metadata, viewport } from "./metadata";
import { themeColorEntries } from "./testing/theme-colors";

describe("product identity metadata", () => {
  it("names the product as the Agent Discussion Room in title, description, and application name", () => {
    expect(metadata.title).toBe("Agent Discussion Room");
    expect(metadata.applicationName).toBe("Agent Discussion Room");
    expect(metadata.description).toContain("Agent Discussion Room");
    expect(metadata.description).not.toContain("Create Next App");
    expect(metadata.description).not.toContain("Generated by create next app");
  });

  it("declares mobile and theme behavior for light and dark systems", () => {
    expect(viewport.width).toBe("device-width");
    expect(viewport.initialScale).toBe(1);
    expect(viewport.colorScheme).toBe("light dark");

    const themeColors = themeColorEntries(viewport);
    expect(themeColors.map((entry) => entry.media)).toEqual([
      "(prefers-color-scheme: light)",
      "(prefers-color-scheme: dark)",
    ]);
    expect(themeColors.every((entry) => /^#[0-9a-fA-F]{6}$/.test(entry.color))).toBe(true);
  });
});
